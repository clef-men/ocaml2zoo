open Implementation
open Mode

let transl_constructor constr : Rocq.zoo_constructor =
  { zoo_constructor_tag= constr.constructor_tag
  ; zoo_constructor_constancy= constr.constructor_constancy
  }

let transl_typ ~mode lpath kind ty =
  let lpath =
    match kind with
    | Type_normal ->
        lpath
    | Type_inline tag ->
        Lpath.Dot (lpath, tag)
  in
  let qualif : Rocq.qualification =
    match mode with
    | Types ->
        Nonqualified
    | Code ->
        Qualified
    | Opaque ->
        assert false
  in
  match ty with
  | Type_record (mut, flds) ->
      Rocq.Zoo_type (qualif, lpath, Zoo_record (mut, flds))
  | Type_variant constrs ->
      let constrs = constrs |> List.map transl_constructor in
      Rocq.Zoo_type (qualif, lpath, Zoo_variant constrs)
let transl_typ ~mode path kind ty =
  match mode with
  | Types
  | Code ->
      [transl_typ ~mode path kind ty]
  | Opaque ->
      []

let transl_value_code = function
  | Val_expr (path, expr) ->
      Rocq.Zoo_val (path, expr)
  | Val_fun (path, params, expr) ->
      Rocq.Zoo_fun (path, params, expr)
  | Val_recs recs ->
      Rocq.Zoo_recs recs
  | Val_opaque path ->
      Rocq.Zoo_parameter path
let transl_value_opaque path =
  Rocq.Opaque path
let transl_value_opaque = function
  | Val_expr (path, _)
  | Val_fun (path, _, _)
  | Val_recs [path, _, _, _]
  | Val_opaque path ->
      [transl_value_opaque path]
  | Val_recs recs ->
      recs |> List.map @@ fun (path, _var, _bdrs, _expr) ->
        transl_value_opaque path
let transl_value ~mode val_ =
  match mode with
  | Types ->
      []
  | Code ->
      [transl_value_code val_]
  | Opaque ->
      transl_value_opaque val_

let transl_declaration ~mode = function
  | Type (path, kind, ty) ->
      transl_typ ~mode path kind ty
  | Val val_ ->
      transl_value ~mode val_

let prelude ~mode =
  [ Rocq.Comment "This file was generated by ocaml2zoo."
  ; Rocq.Newline
  ] @
  match mode with
  | Types
  | Code ->
      [ Rocq.Require (Require_import, "zoo.prelude")
      ; Rocq.Require (Require_import, "zoo.plugin")
      ; Rocq.Require (Require_import, "zoo.language.notations")
      ; Rocq.Require (Require_import, "zoo.language.typeclasses")
      ]
  | Opaque ->
      []
let postlude ~mode =
  match mode with
  | Types
  | Code ->
      [ Rocq.Require (Require_import, "zoo.options")
      ]
  | Opaque ->
      []
let dependencies ~mode t =
  match mode with
  | Types
  | Code ->
      let require_kind : Rocq.require_kind =
        match mode with
        | Types ->
            Require_export
        | Code ->
            Require_import
        | Opaque ->
            assert false
      in
      t
      |> Dependencies.of_ast
      |> Dependencies.to_rocq ~require_kind
  | Opaque ->
      [ Dependency.make t.library t.module_ ~mode:Code
        |> Dependency.to_rocq ~require_kind:Require_import
      ]
let body ~mode t =
  let body = t.declarations |> List.map (transl_declaration ~mode) in
  let body = List.filter ((<>) []) body in
  let body =
    match mode with
    | Types
    | Code ->
        List.interleave ~sep:[Rocq.Newline] body
    | Opaque ->
        body
  in
  body
let transl ~mode t =
  List.concat @@
    [ prelude ~mode
    ; dependencies ~mode t
    ; postlude ~mode
    ; [Rocq.Newline]
    ] @
    body ~mode t
