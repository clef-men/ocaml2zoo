open Implementation
open Mode

module Separator =
  Rocq.Separator

module Type = struct
  let value =
    "val"
end

module Custom_entry = struct
  let recs =
    Printf.sprintf "zoo%srecs"
      Separator.cdot1
end

let transl_constructor constr : Rocq.zoo_constructor =
  { zoo_constructor_tag= constr.constructor_tag
  ; zoo_constructor_constancy= constr.constructor_constancy
  }

let transl_typ ~mode lpath kind ty =
  let lpath =
    match kind with
    | Type_normal ->
        lpath
    | Type_inline tag ->
        Lpath.Dot (lpath, tag)
  in
  let qualif : Rocq.qualification =
    match mode with
    | Types ->
        Nonqualified
    | Code ->
        Qualified
    | Opaque ->
        assert false
  in
  match ty with
  | Type_record (mut, flds) ->
      Rocq.Zoo_type (qualif, lpath, Zoo_record (mut, flds))
  | Type_variant constrs ->
      let constrs = constrs |> List.map transl_constructor in
      Rocq.Zoo_type (qualif, lpath, Zoo_variant constrs)
let transl_typ ~mode path kind ty =
  match mode with
  | Types
  | Code ->
      [transl_typ ~mode path kind ty]
  | Opaque ->
      []

let transl_value_code ~mod_ ~gen = function
  | Val_expr (path, expr) ->
      [ Rocq.Definition
        ( Locality_normal
        , Lpath.(path |> to_string ~sep:Separator.cdot2 ~mod_)
        , Some Type.value
        , fun ppf () ->
            Fmt.box (Implementation_pp.pp_expression ~mod_) ppf expr
        )
      ]
  | Val_fun (path, params, expr) ->
      [ Rocq.Definition
        ( Locality_normal
        , Lpath.(path |> to_string ~sep:Separator.cdot2 ~mod_)
        , Some Type.value
        , fun ppf () ->
            Implementation_pp.pp_fun ~mod_ ppf (path, params, expr)
        )
      ]
  | Val_recs [path, var, params, body] ->
      [ Rocq.Definition
        ( Locality_normal
        , Lpath.(path |> to_string ~sep:Separator.cdot2 ~mod_)
        , Some Type.value
        , fun ppf () ->
            Implementation_pp.pp_rec ~mod_ ppf (path, var, params, body)
        )
      ]
  | Val_recs recs ->
      let id = Generator.next gen in
      List.concat
      [ [ Rocq.Definition
          ( Locality_local
          , Printf.sprintf "__%s%s%i"
              Custom_entry.recs
              Separator.cdot1
              id
          , None
          , fun ppf () ->
              Fmt.pf ppf "@[<v>( %a@,)%%%s@]"
                (Implementation_pp.pp_recs ~mod_) recs
                Custom_entry.recs
          )
        ]
      ; recs |> List.mapi (fun i (path, _, _, _) ->
          Rocq.Definition
          ( Locality_normal
          , Lpath.(path |> to_string ~sep:Separator.cdot2 ~mod_)
          , None
          , fun ppf () ->
              Fmt.pf ppf "ValRecs %i __%s%s%i"
                i
                Custom_entry.recs
                Separator.cdot1
                id
          )
        )
      ; recs |> List.mapi (fun i (path, _, _, _) ->
          Rocq.Instance
          ( Locality_global
          , None
          , fun ppf () ->
              Fmt.pf ppf "@[<v>AsValRecs'@,  @[<v>%a@,%i@,__%s%s%i@,[ %a@,]@]@]"
                (Lpath.pp ~sep:Separator.cdot2 ~mod_) path
                i
                Custom_entry.recs
                Separator.cdot1
                id
                Fmt.(
                  list ~sep:(any "@,; ") @@ fun ppf (path, _, _, _) ->
                    Lpath.pp ~sep:Separator.cdot2 ~mod_ ppf path
                ) recs
          )
        )
      ]
  | Val_opaque path ->
      [ Rocq.Parameter
        ( Lpath.(path |> to_string ~sep:Separator.cdot2 ~mod_)
        , Type.value
        )
      ]
let transl_value_opaque ~mod_ path =
  Rocq.Opaque
  ( Locality_global
  , Lpath.(path |> cons mod_ |> to_string ~sep:Separator.cdot2)
  )
let transl_value_opaque ~mod_ = function
  | Val_expr (path, _)
  | Val_fun (path, _, _)
  | Val_recs [path, _, _, _]
  | Val_opaque path ->
      [transl_value_opaque ~mod_ path]
  | Val_recs recs ->
      recs |> List.map @@ fun (path, _var, _bdrs, _expr) ->
        transl_value_opaque ~mod_ path
let transl_value ~mod_ ~mode ~gen val_ =
  match mode with
  | Types ->
      []
  | Code ->
      transl_value_code ~mod_ ~gen val_
  | Opaque ->
      transl_value_opaque ~mod_ val_

let transl_declaration ~mod_ ~mode ~gen = function
  | Type (path, kind, ty) ->
      transl_typ ~mode path kind ty
  | Val val_ ->
      transl_value ~mod_ ~mode ~gen val_

let prelude ~mode =
  [ Rocq.Comment "This file was generated by ocaml2zoo."
  ; Rocq.Newline
  ] @
  match mode with
  | Types
  | Code ->
      [ Rocq.Require (Require_import, "zoo.prelude")
      ; Rocq.Require (Require_import, "zoo.plugin")
      ; Rocq.Require (Require_import, "zoo.language.notations")
      ; Rocq.Require (Require_import, "zoo.language.typeclasses")
      ]
  | Opaque ->
      []
let postlude ~mode =
  match mode with
  | Types
  | Code ->
      [ Rocq.Require (Require_import, "zoo.options")
      ]
  | Opaque ->
      []
let dependencies ~mode t =
  match mode with
  | Types
  | Code ->
      let require_kind : Rocq.require_kind =
        match mode with
        | Types ->
            Require_export
        | Code ->
            Require_import
        | Opaque ->
            assert false
      in
      t
      |> Dependencies.of_ast
      |> Dependencies.to_rocq ~require_kind
  | Opaque ->
      [ Dependency.make t.library t.module_ ~mode:Code
        |> Dependency.to_rocq ~require_kind:Require_import
      ]
let body ~mode t =
  let body =
    let gen = Generator.create () in
    t.declarations |> List.map @@
      transl_declaration ~mod_:t.module_ ~mode ~gen
  in
  let body = List.filter ((<>) []) body in
  let body =
    match mode with
    | Types
    | Code ->
        List.interleave ~sep:[Rocq.Newline] body
    | Opaque ->
        body
  in
  body
let transl ~mode t =
  List.concat @@
    [ prelude ~mode
    ; dependencies ~mode t
    ; postlude ~mode
    ; [Rocq.Newline]
    ] @
    body ~mode t
